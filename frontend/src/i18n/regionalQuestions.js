/**
 * Resolves question text for any supported Indian language with fallback to Hindi / English
 */
export const getRegionalQuestionText = (category, questionKey, langCode, patientName = 'मरीज') => {
  const protocol = REGIONAL_QUESTIONS[category] || REGIONAL_QUESTIONS.GENERAL;
  const question = protocol[questionKey];
  if (!question) return '';

  const raw = question[langCode] || question.hi || question.en;
  if (typeof raw === 'function') {
    return raw(patientName);
  }
  return raw || '';
};

